#!/usr/bin/env python3
"""Convert the old Access weighbridge DB (EXCEL.mdb) into a MySQL/MariaDB
import script for the weighbridge_db schema (structure_1.8.sql).

Usage:  python mdb_to_sql.py EXCEL.mdb migrate_data.sql
Needs:  pip install access-parser
"""
import sys
from datetime import datetime
from access_parser import AccessParser

SINGLE_STATUS = "pending"      # tickets with only one weighment
DONE_STATUS = "completed"      # tickets with both weighments
SCALE = 10000                  # Access Currency columns are stored x10000

def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"

def money(v):
    return round((v or 0) / SCALE, 2)

def clean(s):
    s = (s or "").strip()
    return None if s in ("", "-") else s

def as_date(d):
    return d.date() if isinstance(d, datetime) else datetime.strptime(str(d)[:10], "%Y-%m-%d").date()

def when(date, t):
    if not date or not (t or "").strip():
        return None
    tm = datetime.strptime(t.strip(), "%I:%M:%S %p").time()
    return datetime.combine(as_date(date), tm).strftime("%Y-%m-%d %H:%M:%S")

def main(mdb, out):
    db = AccessParser(mdb)
    t = db.parse_table("TRANS_MAIN")
    n = len(t["TRANS_ID"])
    rows = [{k: t[k][i] for k in t} for i in range(n)]
    rows.sort(key=lambda r: r["TS_NO"])

    stg = []
    for r in rows:
        w1, w2 = money(r["GROSS_WT"]), money(r["TARE_WT"])   # 1st / 2nd weighing
        single = bool(r["PEND_FW"]) or w2 == 0
        veh = (clean(r["VEH_NO"]) or "UNKNOWN").upper().replace(" ", "")[:20]
        t1 = when(r["TRANS_DATE"], r["TIME_GROSS"])
        t2 = None if single else when(r["TRANS_DATE"], r["TIME_TARE"])
        stg.append((
            r["TS_NO"], r["TRANS_ID"], veh,
            clean(r["Party"]), clean(r["Material"]),
            clean(r["REMARKS"]), w1, t1,
            None if single else w2, t2,
            None if single else round(abs(w1 - w2), 2),
            money(r["Charges"]),
            SINGLE_STATUS if single else DONE_STATUS,
            as_date(r["TRANS_DATE"]).strftime("%Y-%m-%d 00:00:00"),
        ))

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        w("-- Generated by mdb_to_sql.py. Run against weighbridge_db (structure 1.8).\n")
        w("SET NAMES utf8mb4;\nSTART TRANSACTION;\n\n")
        w("SET @serial_base := (SELECT COALESCE(MAX(serial_no),0) FROM transactions);\n\n")
        w("DROP TEMPORARY TABLE IF EXISTS mig_stage;\n")
        w("""CREATE TEMPORARY TABLE mig_stage (
  ts_no INT NOT NULL PRIMARY KEY, old_id INT, vehicle_no VARCHAR(20),
  party VARCHAR(100), material VARCHAR(100), remarks VARCHAR(255),
  w1 DECIMAL(10,2), dt1 DATETIME, w2 DECIMAL(10,2) NULL, dt2 DATETIME NULL,
  net DECIMAL(10,2) NULL, charges DECIMAL(10,2), status VARCHAR(30), created DATETIME
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n""")
        for i in range(0, len(stg), 500):
            w("INSERT INTO mig_stage VALUES\n")
            w(",\n".join("(" + ",".join(q(x) for x in s) + ")" for s in stg[i:i+500]))
            w(";\n")
        w("""
INSERT IGNORE INTO vehicles (vehicle_no) SELECT DISTINCT vehicle_no FROM mig_stage;
INSERT IGNORE INTO parties (party_name) SELECT DISTINCT party FROM mig_stage WHERE party IS NOT NULL;
INSERT IGNORE INTO materials (material_name) SELECT DISTINCT material FROM mig_stage WHERE material IS NOT NULL;

INSERT INTO transactions
 (serial_no, vehicle_id, party_id, material_id, remarks,
  first_weight, first_datetime, second_weight, second_datetime, net_weight,
  charges_first, charges_second, status, created_at,
  gst_amount_first, gst_amount_second, gst_amount, total_amount, net_total)
SELECT @serial_base + s.ts_no, v.id, p.id, m.id, s.remarks,
  s.w1, s.dt1, s.w2, s.dt2, s.net,
  s.charges, 0, s.status, s.created,
  0, 0, 0, s.charges, s.net
FROM mig_stage s
JOIN vehicles v ON v.vehicle_no = s.vehicle_no
LEFT JOIN parties p ON p.party_name = s.party
LEFT JOIN materials m ON m.material_name = s.material
ORDER BY s.ts_no;

INSERT INTO weighment_entries
 (transaction_id, entry_type, weight, charges, gst_percent, gst_amount, total_amount,
  payment_mode, created_at, stage, weight_value)
SELECT t.id, 'first', s.w1, s.charges, NULL, 0, s.charges, 'cash', COALESCE(s.dt1, s.created), 'first', s.w1
FROM mig_stage s JOIN transactions t ON t.serial_no = @serial_base + s.ts_no;

INSERT INTO weighment_entries
 (transaction_id, entry_type, weight, charges, gst_percent, gst_amount, total_amount,
  payment_mode, created_at, stage, weight_value)
SELECT t.id, 'second', s.w2, 0, NULL, 0, 0, 'cash', COALESCE(s.dt2, s.created), 'second', s.w2
FROM mig_stage s JOIN transactions t ON t.serial_no = @serial_base + s.ts_no
WHERE s.w2 IS NOT NULL;

DROP TEMPORARY TABLE mig_stage;
COMMIT;
""")
    print(f"{len(stg)} transactions written to {out}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
